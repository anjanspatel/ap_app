// One-time migration: reads existing accounts + saved lookups out of
// Supabase Postgres and writes a SQL file you load into D1. Doesn't touch
// D1 directly — keeps this script's only dependency on Supabase, so it can
// run from any machine with the connection string, and you can review the
// generated SQL before it touches your new database.
//
// Usage:
//   cd worker
//   npm install pg
//   SUPABASE_DB_URL="postgresql://postgres:<password>@<host>:5432/postgres" node migrate-from-supabase.js
//   wrangler d1 execute ap-workspace --remote --file=./migration-data.sql
//
// Find SUPABASE_DB_URL in the Supabase dashboard: Settings → Database →
// Connection string ("URI" tab, use the direct connection, not the pooler).

import pg from 'pg';
import { writeFileSync } from 'fs';

const dbUrl = process.env.SUPABASE_DB_URL;
if (!dbUrl) {
  console.error('Set SUPABASE_DB_URL to your Supabase Postgres connection string first.');
  process.exit(1);
}

function sqlStr(v) {
  if (v === null || v === undefined) return 'NULL';
  return "'" + String(v).replace(/'/g, "''") + "'";
}
function sqlBool01(v) {
  return v ? 1 : 0;
}

async function main() {
  const client = new pg.Client({ connectionString: dbUrl, ssl: { rejectUnauthorized: false } });
  await client.connect();

  const { rows: users } = await client.query(`
    select id, email, encrypted_password, raw_app_meta_data, raw_user_meta_data,
           banned_until, created_at, last_sign_in_at
    from auth.users
  `);

  const { rows: lookups } = await client.query(`
    select id, user_id, tool, label, params, result_summary, created_at
    from public.saved_lookups
  `);

  await client.end();

  const lines = [];
  lines.push('-- Generated by migrate-from-supabase.js — review before running.');
  lines.push(`-- ${users.length} users, ${lookups.length} saved lookups.`);
  lines.push('');

  for (const u of users) {
    const appMeta = u.raw_app_meta_data || {};
    const userMeta = u.raw_user_meta_data || {};
    const banned = u.banned_until && u.banned_until !== 'none' ? new Date(u.banned_until).toISOString() : null;
    lines.push(
      `insert into users (id, email, password_hash, first_name, last_name, is_admin, verified_by_id, verified_by_name, account_number, banned_until, created_at, last_sign_in_at) values (` +
        [
          sqlStr(u.id),
          sqlStr(u.email),
          sqlStr(u.encrypted_password),
          sqlStr(userMeta.first_name || null),
          sqlStr(userMeta.last_name || null),
          sqlBool01(appMeta.is_admin === true),
          sqlStr(userMeta.verified_by_id || null),
          sqlStr(userMeta.verified_by_name || null),
          sqlStr(userMeta.account_number || null),
          sqlStr(banned),
          sqlStr(u.created_at ? new Date(u.created_at).toISOString() : new Date().toISOString()),
          sqlStr(u.last_sign_in_at ? new Date(u.last_sign_in_at).toISOString() : null),
        ].join(', ') +
        ');'
    );
  }

  lines.push('');
  for (const l of lookups) {
    lines.push(
      `insert into saved_lookups (id, user_id, tool, label, params, result_summary, created_at) values (` +
        [
          sqlStr(l.id),
          sqlStr(l.user_id),
          sqlStr(l.tool),
          sqlStr(l.label || null),
          sqlStr(JSON.stringify(l.params || {})),
          sqlStr(l.result_summary || null),
          sqlStr(l.created_at ? new Date(l.created_at).toISOString() : new Date().toISOString()),
        ].join(', ') +
        ');'
    );
  }

  writeFileSync('migration-data.sql', lines.join('\n') + '\n');
  console.log(`Wrote migration-data.sql — ${users.length} users, ${lookups.length} lookups.`);
  console.log('Review it, then run: wrangler d1 execute ap-workspace --remote --file=./migration-data.sql');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
